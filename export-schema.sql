-- Read-only: prints the whole live database structure of the "public" schema as SQL
-- (tables, columns, keys, indexes, functions, triggers, security rules, live updates). No data.
-- Run in Supabase › SQL Editor, then in the results panel use Export › Download CSV; the single cell is the new schema-live file.
with
tbl as (
  select c.oid, c.relname, c.relrowsecurity from pg_class c
  where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
fn as (
  select p.oid, p.proname from pg_proc p
  where p.pronamespace = 'public'::regnamespace and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
seq as (
  select c.relname from pg_class c
  where c.relnamespace = 'public'::regnamespace and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype in ('a', 'i', 'e'))  -- not owned by an identity column
),
parts as (
  select 0 as ord, '' as k, E'-- Live schema of the Tcipher workspace (public), exported ' || to_char(now() at time zone 'Asia/Kolkata', 'YYYY-MM-DD HH24:MI') || E' IST\nset check_function_bodies = off;' as part
  union all
  select 1, relname, 'create sequence if not exists public.' || quote_ident(relname) || ';' from seq
  union all
  -- tables with every column, exact types, identity and defaults
  select 2, t.relname, 'create table if not exists public.' || quote_ident(t.relname) || E' (\n  ' ||
    string_agg(quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod) ||
      case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end ||
      case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
           when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end ||
      case when a.attnotnull then ' not null' else '' end,
      E',\n  ' order by a.attnum) || E'\n);'
  from tbl t join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
  group by t.relname
  union all
  -- the same columns as "add column if not exists", so running it on an older database fills in what's missing
  select 3, t.relname, 'alter table public.' || quote_ident(t.relname) || ' add column if not exists ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod) ||
    case when ad.adbin is not null and a.attgenerated = '' then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end || ';'
  from tbl t join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
  where a.attidentity = ''
  union all
  select 4, fn.proname, pg_get_functiondef(fn.oid) || ';' from fn
  union all
  -- keys and checks first, foreign keys after
  select case when k.contype = 'f' then 6 else 5 end, t.relname || k.conname,
    'do $x$ begin alter table public.' || quote_ident(t.relname) || ' add constraint ' || quote_ident(k.conname) || ' ' || pg_get_constraintdef(k.oid) ||
    '; exception when duplicate_object or duplicate_table or invalid_table_definition then null; end $x$;'
  from pg_constraint k join tbl t on t.oid = k.conrelid
  union all
  select 7, i.tablename || i.indexname, replace(replace(i.indexdef, 'CREATE INDEX ', 'CREATE INDEX IF NOT EXISTS '), 'CREATE UNIQUE INDEX ', 'CREATE UNIQUE INDEX IF NOT EXISTS ') || ';'
  from pg_indexes i where i.schemaname = 'public' and i.tablename in (select relname from tbl)
    and not exists (select 1 from pg_constraint k where k.conname = i.indexname and k.connamespace = 'public'::regnamespace)
  union all
  select 8, t.relname || tg.tgname, 'drop trigger if exists ' || quote_ident(tg.tgname) || ' on public.' || quote_ident(t.relname) || E';\n' || pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg join tbl t on t.oid = tg.tgrelid where not tg.tgisinternal
  union all
  select 9, relname, 'alter table public.' || quote_ident(relname) || ' enable row level security;' from tbl where relrowsecurity
  union all
  select 10, p.tablename || p.policyname, 'drop policy if exists ' || quote_ident(p.policyname) || ' on public.' || quote_ident(p.tablename) || E';\ncreate policy ' || quote_ident(p.policyname) || ' on public.' || quote_ident(p.tablename) ||
    ' as ' || p.permissive || ' for ' || p.cmd || ' to ' || array_to_string(p.roles, ', ') ||
    coalesce(' using (' || p.qual || ')', '') || coalesce(' with check (' || p.with_check || ')', '') || ';'
  from pg_policies p where p.schemaname = 'public'
  union all
  select 11, v.viewname, 'create or replace view public.' || quote_ident(v.viewname) || ' as ' || v.definition
  from pg_views v where v.schemaname = 'public'
  union all
  select 12, pt.tablename, 'do $x$ begin alter publication supabase_realtime add table public.' || quote_ident(pt.tablename) || '; exception when duplicate_object then null; end $x$;'
  from pg_publication_tables pt where pt.pubname = 'supabase_realtime' and pt.schemaname = 'public'
)
select string_agg(part, E'\n\n' order by ord, k) as sql from parts;
